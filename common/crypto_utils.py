"""
crypto_utils.py — All cryptographic primitives for the Secure Healthcare
File-Sharing Protocol.

Primitives implemented here:
    1. AES-256-GCM  — authenticated file encryption with AAD binding
    2. RSA-OAEP     — key wrapping / unwrapping
    3. RSA-PSS      — digital signatures (authentication + non-repudiation)
    4. scrypt        — memory-hard password hashing
    5. PBKDF2-HMAC-SHA256 — alternative password KDF (spec requirement)
    6. HMAC-SHA256  — session token signing
    7. RSA key-pair generation and PEM serialisation

Security invariants enforced by this module:
    - GCM nonces are always freshly generated by os.urandom(); reuse is
      structurally impossible because we never accept an externally supplied
      nonce for encryption.
    - Private keys are ONLY serialised using BestAvailableEncryption
      (scrypt-backed PKCS#8), never unencrypted.
    - Constant-time comparison is used wherever timing side-channels matter.
    - No algorithm from the prohibited list (ECB, MD5, SHA-1, PKCS1v15)
      appears anywhere in this file.
"""

import hashlib
import hmac
import os
import secrets
from dataclasses import dataclass

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa
from cryptography.hazmat.primitives.asymmetric.rsa import (
    RSAPrivateKey,
    RSAPublicKey,
)
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

from common.config import (
    AES_KEY_SIZE_BYTES,
    GCM_NONCE_SIZE_BYTES,
    PBKDF2_HASH,
    PBKDF2_ITERATIONS,
    RSA_KEY_SIZE_BITS,
    RSA_PUBLIC_EXPONENT,
    SCRYPT_KEY_LEN,
    SCRYPT_N,
    SCRYPT_P,
    SCRYPT_R,
    SCRYPT_SALT_SIZE,
)

# ---------------------------------------------------------------------------
# Public data types
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class EncryptedFile:
    """
    Result of AES-256-GCM encryption.

    Fields:
        ciphertext: Raw ciphertext bytes (includes the GCM authentication tag
                    appended by AESGCM.encrypt()).
        nonce:      96-bit (12-byte) random IV used for this encryption.
                    Must be stored alongside the ciphertext for decryption.
        aad:        The Associated Data that was authenticated but NOT encrypted.
                    Must be provided identically during decryption; any
                    modification causes tag verification failure.
    """
    ciphertext: bytes
    nonce: bytes
    aad: bytes


@dataclass(frozen=True)
class PasswordHash:
    """Scrypt-derived key + parameters, ready for persistence."""
    derived_key: bytes    # 256-bit key (used as the stored verifier)
    salt: bytes           # 256-bit random salt
    n: int
    r: int
    p: int


# ---------------------------------------------------------------------------
# 1. AES-256-GCM — File Encryption
# ---------------------------------------------------------------------------

def aes_gcm_encrypt(plaintext: bytes, aad: bytes) -> EncryptedFile:
    """
    Encrypt *plaintext* with a freshly generated AES-256-GCM key and nonce.

    WHY AAD (Associated Data):
        GCM authenticates AAD in the tag computation without encrypting it.
        We bind metadata (file_id, sender_id, timestamp) as AAD so that an
        attacker cannot attach the ciphertext to a different file record or
        claim a different sender — the tag will fail verification.

    Args:
        plaintext: Raw file bytes to encrypt.
        aad:       Serialised metadata bytes bound to this ciphertext.
                   Must be identical on decryption.

    Returns:
        EncryptedFile containing ciphertext (with embedded 16-byte GCM tag),
        nonce, and aad.

    Raises:
        ValueError: If plaintext is empty.
    """
    if not plaintext:
        raise ValueError("Refusing to encrypt empty plaintext.")

    # Generate a fresh 256-bit AES key — never reuse a key+nonce pair.
    # os.urandom() uses the OS CSPRNG (CryptGenRandom on Windows,
    # getrandom(2) on Linux), which is seeded from hardware entropy.
    key: bytes = os.urandom(AES_KEY_SIZE_BYTES)

    # 96-bit nonce: probability of collision with a single key is negligible
    # (birthday bound ≈ 2^48 encryptions), and NIST recommends fresh random
    # nonces over counters when the key is single-use (as here).
    nonce: bytes = os.urandom(GCM_NONCE_SIZE_BYTES)

    aesgcm = AESGCM(key)
    # AESGCM.encrypt() returns ciphertext || 16-byte tag concatenated.
    ciphertext: bytes = aesgcm.encrypt(nonce, plaintext, aad)

    return EncryptedFile(ciphertext=ciphertext, nonce=nonce, aad=aad), key


def aes_gcm_decrypt(
    encrypted: EncryptedFile,
    key: bytes,
) -> bytes:
    """
    Decrypt and authenticate an AES-256-GCM ciphertext.

    The GCM tag covers both the ciphertext and the AAD.  Any modification
    to either raises InvalidTag — making integrity verification automatic.

    Args:
        encrypted: EncryptedFile produced by aes_gcm_encrypt().
        key:       The 256-bit AES key used during encryption.

    Returns:
        Decrypted plaintext bytes.

    Raises:
        cryptography.exceptions.InvalidTag: If authentication fails (tampered
            ciphertext, wrong key, wrong nonce, or modified AAD).
        ValueError: If key length is wrong.
    """
    if len(key) != AES_KEY_SIZE_BYTES:
        raise ValueError(
            f"AES key must be {AES_KEY_SIZE_BYTES} bytes, got {len(key)}."
        )

    aesgcm = AESGCM(key)
    # InvalidTag is raised automatically if decryption fails — no manual tag
    # comparison needed.
    return aesgcm.decrypt(encrypted.nonce, encrypted.ciphertext, encrypted.aad)


# ---------------------------------------------------------------------------
# 2. RSA Key Generation and Serialisation
# ---------------------------------------------------------------------------

def generate_rsa_keypair() -> tuple[RSAPrivateKey, RSAPublicKey]:
    """
    Generate a 3072-bit RSA key pair.

    WHY 3072 bits:
        Provides ~128-bit classical security (matching AES-256).
        NIST SP 800-57 Part 1 Rev 5 places 3072-bit RSA in security
        category "≥112" through 2031+.  2048-bit is only good to 2030.

    Returns:
        Tuple of (private_key, public_key).
    """
    private_key: RSAPrivateKey = rsa.generate_private_key(
        public_exponent=RSA_PUBLIC_EXPONENT,
        key_size=RSA_KEY_SIZE_BITS,
    )
    return private_key, private_key.public_key()


def serialize_private_key(private_key: RSAPrivateKey, password: bytes) -> bytes:
    """
    Serialise a private key to an encrypted PKCS#8 PEM blob.

    WHY BestAvailableEncryption:
        The 'cryptography' library maps BestAvailableEncryption to AES-256-CBC
        with an scrypt-derived key (in modern versions).  Private keys are
        NEVER stored in plaintext — a stolen key file without the password
        is useless.

    Args:
        private_key: The RSA private key to serialise.
        password:    Passphrase bytes used to encrypt the PEM.

    Returns:
        PEM-encoded bytes (encrypted PKCS#8 PrivateKeyInfo).

    Raises:
        TypeError: If password is not bytes.
    """
    if not isinstance(password, bytes):
        raise TypeError("Password must be bytes.")
    if not password:
        raise ValueError("Refusing to serialise private key with empty password.")

    return private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        # BestAvailableEncryption uses scrypt internally in cryptography >= 41
        encryption_algorithm=serialization.BestAvailableEncryption(password),
    )


def load_private_key(pem_data: bytes, password: bytes) -> RSAPrivateKey:
    """
    Deserialise and decrypt a private key from a PEM blob.

    Args:
        pem_data: PEM bytes as returned by serialize_private_key().
        password: Passphrase used during serialisation.

    Returns:
        The decrypted RSAPrivateKey object.

    Raises:
        ValueError: If the password is wrong or the PEM is malformed.
    """
    return serialization.load_pem_private_key(pem_data, password=password)


def serialize_public_key(public_key: RSAPublicKey) -> bytes:
    """
    Serialise a public key to an unencrypted SubjectPublicKeyInfo PEM blob.

    Public keys carry no secret material so no encryption is needed.
    """
    return public_key.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )


def load_public_key(pem_data: bytes) -> RSAPublicKey:
    """Load an RSA public key from a PEM blob."""
    return serialization.load_pem_public_key(pem_data)


# ---------------------------------------------------------------------------
# 3. RSA-OAEP Key Wrapping / Unwrapping
# ---------------------------------------------------------------------------

def rsa_oaep_wrap(aes_key: bytes, recipient_public_key: RSAPublicKey) -> bytes:
    """
    Wrap (encrypt) an AES key using the recipient's RSA public key via OAEP.

    WHY RSA-OAEP instead of RSA-PKCS1v15:
        PKCS#1 v1.5 encryption is vulnerable to the Bleichenbacher adaptive
        chosen-ciphertext attack (1998) and its many variants (ROBOT, 2018).
        OAEP is provably IND-CCA2 secure under the RSA assumption.
        We use SHA-256 for both the main hash and the MGF1 mask, per
        NIST SP 800-56B Rev 2 recommendation.

    WHY wrap per recipient rather than per file:
        The file is encrypted once. Sharing with N recipients costs N RSA
        operations (cheap), not N re-encryptions of the file (expensive and
        risky — each re-encryption creates a new ciphertext to audit).

    Args:
        aes_key:              The 256-bit AES key to protect.
        recipient_public_key: The RSA public key of the authorised recipient.

    Returns:
        RSA-OAEP ciphertext (same length as the RSA modulus, 384 bytes for
        3072-bit keys).

    Raises:
        ValueError: If aes_key has the wrong length.
    """
    if len(aes_key) != AES_KEY_SIZE_BYTES:
        raise ValueError(
            f"AES key must be {AES_KEY_SIZE_BYTES} bytes, got {len(aes_key)}."
        )

    return recipient_public_key.encrypt(
        aes_key,
        padding.OAEP(
            mgf=padding.MGF1(algorithm=hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None,
        ),
    )


def rsa_oaep_unwrap(
    wrapped_key: bytes, recipient_private_key: RSAPrivateKey
) -> bytes:
    """
    Unwrap (decrypt) an AES key using the recipient's RSA private key.

    Args:
        wrapped_key:           Bytes produced by rsa_oaep_wrap().
        recipient_private_key: The matching RSA private key.

    Returns:
        The original 256-bit AES key bytes.

    Raises:
        cryptography.exceptions.InvalidKey / ValueError: On decryption failure.
    """
    return recipient_private_key.decrypt(
        wrapped_key,
        padding.OAEP(
            mgf=padding.MGF1(algorithm=hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None,
        ),
    )


# ---------------------------------------------------------------------------
# 4. RSA-PSS Digital Signatures
# ---------------------------------------------------------------------------

def _pss_padding() -> padding.PSS:
    """
    Return the RSA-PSS padding object used for both signing and verification.

    WHY RSA-PSS instead of PKCS1v15 for signing:
        PSS (Probabilistic Signature Scheme) is provably secure in the random
        oracle model; PKCS#1 v1.5 signatures have no known full-break but lack
        a formal security proof.  FIPS 186-5 (2023) mandates PSS for new
        RSA signature applications.

    WHY MAX_LENGTH salt:
        Maximising the PSS salt length (equal to the hash output length, 32
        bytes for SHA-256) provides the tightest security reduction.
    """
    return padding.PSS(
        mgf=padding.MGF1(hashes.SHA256()),
        # PSS salt length: MAX_LENGTH → 256 bits of randomness in the signature
        salt_length=padding.PSS.MAX_LENGTH,
    )


def rsa_pss_sign(message: bytes, private_key: RSAPrivateKey) -> bytes:
    """
    Sign *message* with RSA-PSS (SHA-256).

    In this protocol the *message* is: ciphertext || nonce || metadata_bytes.
    Binding all three ensures that the signature covers every security-relevant
    field, preventing selective reuse attacks.

    Args:
        message:     The byte string to sign.
        private_key: The signer's RSA private key.

    Returns:
        PSS signature bytes (384 bytes for 3072-bit RSA).

    Raises:
        ValueError: If message is empty.
    """
    if not message:
        raise ValueError("Refusing to sign empty message.")

    return private_key.sign(message, _pss_padding(), hashes.SHA256())


def rsa_pss_verify(
    message: bytes, signature: bytes, public_key: RSAPublicKey
) -> bool:
    """
    Verify an RSA-PSS signature.

    This function is used by:
        - The SERVER on upload: verifies the uploader's identity.
        - The CLIENT on download: verifies non-repudiation (server cannot
          forge a signature it did not produce, so a valid sig proves the
          claimed sender signed the file).

    Args:
        message:    The signed byte string.
        signature:  The PSS signature bytes.
        public_key: The purported signer's RSA public key.

    Returns:
        True if the signature is valid, False otherwise.
        (Never raises — returns False on any verification failure so callers
        can use a simple boolean check without exception handling.)
    """
    try:
        public_key.verify(signature, message, _pss_padding(), hashes.SHA256())
        return True
    except Exception:
        # cryptography raises InvalidSignature on failure; we normalise to bool
        # so upper layers don't accidentally swallow unrelated exceptions.
        return False


# ---------------------------------------------------------------------------
# 5. Password Hashing — scrypt (primary) and PBKDF2 (alternative)
# ---------------------------------------------------------------------------

def scrypt_hash_password(password: str) -> PasswordHash:
    """
    Hash a plaintext password using scrypt.

    WHY NOT plain SHA-256:
        SHA-256 is an unbounded-speed hash; a modern GPU can compute >10^10
        SHA-256 hashes/second, making dictionary attacks trivial.
        scrypt requires O(N * r) memory per guess, parallelism is limited by
        RAM bandwidth, not compute — this is the defining advantage over bcrypt.

    Args:
        password: The user's plaintext password (unicode string).

    Returns:
        PasswordHash with the derived key and parameters for later verification.

    Raises:
        ValueError: If password is empty.
    """
    if not password:
        raise ValueError("Password must not be empty.")

    # 256-bit random salt — unique per user, stored in the database alongside
    # the derived key. Salt prevents rainbow-table attacks and ensures two
    # users with the same password get different stored hashes.
    salt: bytes = os.urandom(SCRYPT_SALT_SIZE)

    kdf = Scrypt(salt=salt, length=SCRYPT_KEY_LEN, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P)
    derived_key: bytes = kdf.derive(password.encode("utf-8"))

    return PasswordHash(derived_key=derived_key, salt=salt, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P)


def scrypt_verify_password(password: str, stored: PasswordHash) -> bool:
    """
    Verify a plaintext password against a stored PasswordHash.

    WHY CONSTANT-TIME COMPARISON:
        A naive ``derived == stored.derived_key`` leaks timing information —
        Python short-circuits the comparison on the first differing byte, so
        an attacker can measure response times to learn the prefix of the
        stored hash.  hmac.compare_digest() is guaranteed to run in constant
        time regardless of where the strings differ.

    Args:
        password: Plaintext password to check.
        stored:   PasswordHash returned by scrypt_hash_password().

    Returns:
        True if the password matches, False otherwise.
    """
    try:
        kdf = Scrypt(
            salt=stored.salt,
            length=SCRYPT_KEY_LEN,
            n=stored.n,
            r=stored.r,
            p=stored.p,
        )
        derived: bytes = kdf.derive(password.encode("utf-8"))
        # Constant-time comparison to prevent timing side-channels
        return hmac.compare_digest(derived, stored.derived_key)
    except Exception:
        return False


def pbkdf2_hash_password(password: str) -> tuple[bytes, bytes]:
    """
    Hash a password with PBKDF2-HMAC-SHA256 (≥ 600,000 iterations).

    Provided as a spec-required alternative to scrypt.  scrypt is preferred
    because it is also memory-hard.

    Args:
        password: The user's plaintext password.

    Returns:
        Tuple of (derived_key_bytes, salt_bytes).
    """
    if not password:
        raise ValueError("Password must not be empty.")

    salt: bytes = os.urandom(SCRYPT_SALT_SIZE)
    kdf = PBKDF2HMAC(
        algorithm=hashes.SHA256(),
        length=SCRYPT_KEY_LEN,
        salt=salt,
        iterations=PBKDF2_ITERATIONS,
    )
    derived_key: bytes = kdf.derive(password.encode("utf-8"))
    return derived_key, salt


def pbkdf2_verify_password(
    password: str, derived_key: bytes, salt: bytes
) -> bool:
    """
    Verify a password against a PBKDF2-derived key (constant-time).

    Args:
        password:    Plaintext password.
        derived_key: Stored derived key bytes.
        salt:        Salt used during hashing.

    Returns:
        True if the password matches.
    """
    try:
        kdf = PBKDF2HMAC(
            algorithm=hashes.SHA256(),
            length=SCRYPT_KEY_LEN,
            salt=salt,
            iterations=PBKDF2_ITERATIONS,
        )
        candidate: bytes = kdf.derive(password.encode("utf-8"))
        return hmac.compare_digest(candidate, derived_key)
    except Exception:
        return False


# ---------------------------------------------------------------------------
# 6. HMAC-SHA256 — Session Token Signing
# ---------------------------------------------------------------------------

def hmac_sign(data: bytes, key: bytes) -> bytes:
    """
    Compute HMAC-SHA256 of *data* using *key*.

    Used to sign session tokens.  HMAC is a PRF — an attacker who does not
    know the key cannot produce a valid MAC for any message they choose,
    even after seeing many valid (message, MAC) pairs.

    Args:
        data: The byte string to authenticate.
        key:  The 256-bit HMAC key (must be kept secret on the server).

    Returns:
        32-byte HMAC digest.
    """
    return hmac.new(key, data, hashlib.sha256).digest()


def hmac_verify(data: bytes, expected_mac: bytes, key: bytes) -> bool:
    """
    Verify an HMAC-SHA256 in constant time.

    Args:
        data:         The byte string that was authenticated.
        expected_mac: The MAC to verify against.
        key:          The HMAC key.

    Returns:
        True if the MAC is valid.
    """
    actual_mac: bytes = hmac_sign(data, key)
    return hmac.compare_digest(actual_mac, expected_mac)


# ---------------------------------------------------------------------------
# 7. Secure Random Helpers
# ---------------------------------------------------------------------------

def generate_session_token_secret() -> bytes:
    """
    Generate a cryptographically secure random key for HMAC token signing.

    Called once at server startup; the key lives only in memory and is
    discarded on shutdown, automatically invalidating all issued tokens.

    Returns:
        32 random bytes (256 bits).
    """
    return secrets.token_bytes(32)


def sha256_digest(data: bytes) -> str:
    """
    Return the hex-encoded SHA-256 digest of *data*.

    Used for the audit log hash chain.  Note: SHA-256 is appropriate here
    because we are hashing log entries (not passwords).  The prohibition on
    "plain SHA-256" in the spec applies only to password storage.

    Args:
        data: Bytes to hash.

    Returns:
        64-character lowercase hex string.
    """
    return hashlib.sha256(data).hexdigest()
