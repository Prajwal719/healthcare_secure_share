"""
generate_certs.py — Local PKI setup for the Secure Healthcare File-Sharing Protocol.

Generates a complete certificate chain entirely with the `cryptography` library —
no openssl subprocess calls, no external tools required.

Certificate Hierarchy:
    HealthcareCA (self-signed, RSA-3072)
        └── healthcare-server (signed by CA, server auth)
        └── client-<name>    (signed by CA, client auth, one per user)

WHY MUTUAL TLS:
    Standard TLS authenticates only the server. Mutual TLS (mTLS) requires
    the client to also present a certificate signed by the trusted CA. This:
      • Prevents any unauthorised client from even opening a connection.
      • Provides a second authentication factor on top of login tokens.
      • Eliminates credential-stuffing and brute-force at the network layer.

WHY RSA-3072 FOR TLS KEYS:
    Consistent with our application-layer key size; the CA key strength sets
    an upper bound on the entire chain's security.

WHY 4096-bit CA KEY:
    The CA is the root of trust for ALL certificates. A compromised CA key
    means all issued certs are untrusted. We use 4096-bit for the CA to give
    it a larger security margin than the end-entity certs.

WHY SEPARATE APPLICATION KEYS:
    TLS certificates authenticate the TLS connection. Application RSA keys
    (generated by generate_user_keys.py) sign/wrap file data. Keeping them
    separate follows the principle of key separation — a TLS key compromise
    does not expose file-encryption capabilities, and vice versa.

Usage:
    cd healthcare_secure_share
    python scripts/generate_certs.py --clients doctor nurse patient admin
    # Or with custom passwords (default: prompts interactively)
    python scripts/generate_certs.py --clients doctor nurse --ca-password capass \\
        --server-password srvpass --client-password clipass

Output (all under certs/):
    ca.key          — Encrypted CA private key (PKCS8, AES-256)
    ca.crt          — CA self-signed certificate (PEM)
    server.key      — Encrypted server private key
    server.crt      — Server certificate signed by CA
    client_<name>.key  — Encrypted client private key
    client_<name>.crt  — Client certificate signed by CA
"""

import argparse
import datetime
import getpass
import ipaddress
import secrets
import sys
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives.asymmetric.rsa import RSAPrivateKey
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

# Project root is two levels up from scripts/
PROJECT_ROOT = Path(__file__).resolve().parent.parent
CERTS_DIR = PROJECT_ROOT / "certs"

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

CA_KEY_SIZE = 4096          # CA key: largest margin (root of trust)
ENTITY_KEY_SIZE = 3072      # Server + client certs: matches application keys
CA_VALIDITY_DAYS = 3650     # 10 years
ENTITY_VALIDITY_DAYS = 365  # 1 year for server and clients

# ---------------------------------------------------------------------------
# Key generation helpers
# ---------------------------------------------------------------------------


def _generate_rsa_key(key_size: int) -> RSAPrivateKey:
    """Generate an RSA private key with a standard public exponent."""
    return rsa.generate_private_key(
        public_exponent=65537,
        key_size=key_size,
    )


def _save_private_key(key: RSAPrivateKey, path: Path, password: bytes) -> None:
    """
    Serialise a private key to an encrypted PKCS8 PEM file.

    WHY BestAvailableEncryption:
        In cryptography >= 38, BestAvailableEncryption uses scrypt-derived
        AES-256-CBC — significantly stronger than the legacy PBE schemes
        (DES3-CBC) used by older OpenSSL-generated PEM files.

    Args:
        key:      The RSA private key.
        path:     Destination file path.
        password: Passphrase bytes.
    """
    pem = key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.BestAvailableEncryption(password),
    )
    path.write_bytes(pem)
    # Restrict permissions: owner read-only (no effect on Windows, documented)
    try:
        path.chmod(0o600)
    except NotImplementedError:
        pass  # Windows: chmod is a no-op, acceptable for course project
    print(f"  Saved key  -> {path.relative_to(PROJECT_ROOT)}")


def _save_certificate(cert: x509.Certificate, path: Path) -> None:
    """Serialise an X.509 certificate to a PEM file."""
    path.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    print(f"  Saved cert -> {path.relative_to(PROJECT_ROOT)}")


# ---------------------------------------------------------------------------
# Certificate builders
# ---------------------------------------------------------------------------


def _build_ca_cert(
    ca_key: RSAPrivateKey,
    common_name: str = "HealthcareSecureShareCA",
    validity_days: int = CA_VALIDITY_DAYS,
) -> x509.Certificate:
    """
    Build a self-signed CA certificate.

    Certificate extensions explained:
      BasicConstraints(ca=True):
          Marks this as a Certificate Authority — without this, TLS stacks
          will refuse to use it as a trust anchor.
      KeyUsage(key_cert_sign=True, crl_sign=True):
          The CA key is only authorised for signing certificates and CRLs —
          it CANNOT be used for key encipherment or digital signatures on data.
          This is the principle of key separation in X.509.
      SubjectKeyIdentifier / AuthorityKeyIdentifier:
          Enable certificate chain building by TLS libraries; required by
          RFC 5280 for CAs.

    Args:
        ca_key:       The CA's RSA private key.
        common_name:  Human-readable CA name.
        validity_days: Certificate validity period.

    Returns:
        Signed X.509 Certificate object.
    """
    now = datetime.datetime.now(datetime.timezone.utc)
    subject = issuer = x509.Name(
        [
            x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "HealthcareSecureShare"),
            x509.NameAttribute(NameOID.COMMON_NAME, common_name),
        ]
    )

    public_key = ca_key.public_key()
    ski = x509.SubjectKeyIdentifier.from_public_key(public_key)

    cert = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(issuer)
        .public_key(public_key)
        .serial_number(secrets.randbits(128))   # Random serial: prevents serial collisions
        .not_valid_before(now)
        .not_valid_after(now + datetime.timedelta(days=validity_days))
        # CA flag — MUST be True for a trust anchor
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        # Key usage: CA may only sign certs and CRLs
        .add_extension(
            x509.KeyUsage(
                digital_signature=False,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,     # Sign subordinate certificates
                crl_sign=True,          # Sign revocation lists
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(ski, critical=False)
        # Self-signed: AKI == SKI
        .add_extension(
            x509.AuthorityKeyIdentifier.from_issuer_public_key(public_key),
            critical=False,
        )
        .sign(ca_key, hashes.SHA256())   # SHA-256 signature; SHA-1 is prohibited
    )
    return cert


def _build_server_cert(
    ca_key: RSAPrivateKey,
    ca_cert: x509.Certificate,
    server_key: RSAPrivateKey,
    common_name: str = "healthcare-server",
    validity_days: int = ENTITY_VALIDITY_DAYS,
) -> x509.Certificate:
    """
    Build a TLS server certificate signed by the CA.

    Certificate extensions explained:
      BasicConstraints(ca=False):
          Prevents a compromised server cert from being used to issue new certs
          (prevents certificate chain extension attacks).
      KeyUsage(digital_signature=True, key_encipherment=True):
          - digital_signature: needed for TLS 1.3 (ECDHE/DHE key exchange).
          - key_encipherment: needed for TLS 1.2 RSA key exchange.
      ExtendedKeyUsage(serverAuth):
          Restricts this cert to TLS server use only — cannot be misused for
          client authentication or code signing.
      SubjectAlternativeName:
          Modern TLS clients validate the SAN, not the CN. We add both
          DNS:localhost and IP:127.0.0.1 to support both hostname and IP
          connection styles on localhost.

    Args:
        ca_key:      CA's private key (for signing).
        ca_cert:     CA's certificate (for issuer + AKI).
        server_key:  Server's RSA private key.
        common_name: Server's hostname.
        validity_days: Certificate validity period.

    Returns:
        Signed X.509 server Certificate object.
    """
    now = datetime.datetime.now(datetime.timezone.utc)
    subject = x509.Name(
        [
            x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "HealthcareSecureShare"),
            x509.NameAttribute(NameOID.COMMON_NAME, common_name),
        ]
    )

    public_key = server_key.public_key()

    cert = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(ca_cert.subject)
        .public_key(public_key)
        .serial_number(secrets.randbits(128))
        .not_valid_before(now)
        .not_valid_after(now + datetime.timedelta(days=validity_days))
        # NOT a CA — cannot issue certificates
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        # Key usage for TLS server
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=True,   # RSA key exchange (TLS 1.2)
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=False,
                crl_sign=False,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        # Extended key usage: server authentication only
        .add_extension(
            x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]),
            critical=False,
        )
        # SAN: both DNS name and IP address for localhost testing
        .add_extension(
            x509.SubjectAlternativeName(
                [
                    x509.DNSName("localhost"),
                    x509.IPAddress(ipaddress.IPv4Address("127.0.0.1")),
                ]
            ),
            critical=False,
        )
        .add_extension(
            x509.SubjectKeyIdentifier.from_public_key(public_key),
            critical=False,
        )
        .add_extension(
            x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_cert.public_key()),
            critical=False,
        )
        .sign(ca_key, hashes.SHA256())
    )
    return cert


def _build_client_cert(
    ca_key: RSAPrivateKey,
    ca_cert: x509.Certificate,
    client_key: RSAPrivateKey,
    username: str,
    validity_days: int = ENTITY_VALIDITY_DAYS,
) -> x509.Certificate:
    """
    Build a TLS client certificate signed by the CA.

    Certificate extensions explained:
      ExtendedKeyUsage(clientAuth):
          Restricts this cert to TLS client authentication — it cannot be
          presented by a server or used for code signing.
      KeyUsage(digital_signature=True):
          Client certs only sign the TLS handshake; no key encipherment needed.
      CN = username:
          The server extracts the CN from the client cert to correlate the TLS
          identity with the application user account.

    Args:
        ca_key:      CA's private key (for signing).
        ca_cert:     CA's certificate (for issuer + AKI).
        client_key:  Client's RSA private key.
        username:    The user identifier (becomes the certificate CN).
        validity_days: Certificate validity period.

    Returns:
        Signed X.509 client Certificate object.
    """
    now = datetime.datetime.now(datetime.timezone.utc)
    subject = x509.Name(
        [
            x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "HealthcareSecureShare"),
            x509.NameAttribute(NameOID.COMMON_NAME, username),   # Used by server to ID client
        ]
    )

    public_key = client_key.public_key()

    cert = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(ca_cert.subject)
        .public_key(public_key)
        .serial_number(secrets.randbits(128))
        .not_valid_before(now)
        .not_valid_after(now + datetime.timedelta(days=validity_days))
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        # Key usage: client auth signature only
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=False,
                crl_sign=False,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        # Extended key usage: client authentication only
        .add_extension(
            x509.ExtendedKeyUsage([ExtendedKeyUsageOID.CLIENT_AUTH]),
            critical=False,
        )
        .add_extension(
            x509.SubjectKeyIdentifier.from_public_key(public_key),
            critical=False,
        )
        .add_extension(
            x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_cert.public_key()),
            critical=False,
        )
        .sign(ca_key, hashes.SHA256())
    )
    return cert


# ---------------------------------------------------------------------------
# Main generation workflow
# ---------------------------------------------------------------------------


def generate_pki(
    client_names: list[str],
    ca_password: bytes,
    server_password: bytes,
    client_password: bytes,
) -> None:
    """
    Run the full PKI generation workflow.

    Creates certs/ directory and generates:
        - CA key + self-signed certificate
        - Server key + certificate signed by CA
        - One client key + certificate per name in client_names

    Args:
        client_names:    List of client usernames (e.g. ["doctor", "nurse"]).
        ca_password:     Password for the CA private key.
        server_password: Password for the server private key.
        client_password: Password for all client private keys (same for demo;
                         in production each client would have a unique password).

    Raises:
        ValueError: If client_names is empty.
    """
    if not client_names:
        raise ValueError("At least one client name must be provided.")

    CERTS_DIR.mkdir(parents=True, exist_ok=True)

    # --- 1. Certificate Authority ---
    print("\n[1/3] Generating Certificate Authority (RSA-4096)...")
    ca_key = _generate_rsa_key(CA_KEY_SIZE)
    ca_cert = _build_ca_cert(ca_key)
    _save_private_key(ca_key, CERTS_DIR / "ca.key", ca_password)
    _save_certificate(ca_cert, CERTS_DIR / "ca.crt")

    # --- 2. Server certificate ---
    print("\n[2/3] Generating server certificate (RSA-3072)...")
    server_key = _generate_rsa_key(ENTITY_KEY_SIZE)
    server_cert = _build_server_cert(ca_key, ca_cert, server_key)
    _save_private_key(server_key, CERTS_DIR / "server.key", server_password)
    _save_certificate(server_cert, CERTS_DIR / "server.crt")

    # --- 3. Client certificates ---
    print(f"\n[3/3] Generating {len(client_names)} client certificate(s) (RSA-3072)...")
    for name in client_names:
        # Sanitise the name to avoid path traversal in filenames
        safe_name = "".join(c for c in name if c.isalnum() or c in "-_")
        if not safe_name:
            print(f"  SKIP: '{name}' contains no valid characters.")
            continue
        print(f"\n  Client: {safe_name}")
        client_key = _generate_rsa_key(ENTITY_KEY_SIZE)
        client_cert = _build_client_cert(ca_key, ca_cert, client_key, safe_name)
        _save_private_key(client_key, CERTS_DIR / f"client_{safe_name}.key", client_password)
        _save_certificate(client_cert, CERTS_DIR / f"client_{safe_name}.crt")

    print("\n[OK] PKI generation complete.")
    print(f"  All files written to: {CERTS_DIR}")
    _print_usage_instructions(client_names)


def _print_usage_instructions(client_names: list[str]) -> None:
    """Print a quick-reference for how to use the generated certs."""
    print("\n--- TLS Configuration ---")
    print("Server ssl.SSLContext:")
    print("  ctx.load_cert_chain('certs/server.crt', 'certs/server.key')")
    print("  ctx.load_verify_locations('certs/ca.crt')")
    print("  ctx.verify_mode = ssl.CERT_REQUIRED")
    print("\nClient ssl.SSLContext (example for 'doctor'):")
    print("  ctx.load_cert_chain('certs/client_doctor.crt', 'certs/client_doctor.key')")
    print("  ctx.load_verify_locations('certs/ca.crt')")


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------


def main() -> None:
    """Parse arguments and run the PKI generator."""
    parser = argparse.ArgumentParser(
        description="Generate a local PKI (CA + server + client certs) for the "
                    "Secure Healthcare File-Sharing Protocol.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--clients",
        nargs="+",
        required=True,
        metavar="NAME",
        help="Usernames to generate client certificates for (e.g. doctor nurse patient admin).",
    )
    parser.add_argument(
        "--ca-password",
        default=None,
        help="Password for the CA private key (prompted if omitted).",
    )
    parser.add_argument(
        "--server-password",
        default=None,
        help="Password for the server private key (prompted if omitted).",
    )
    parser.add_argument(
        "--client-password",
        default=None,
        help="Shared password for all client private keys (prompted if omitted).",
    )
    args = parser.parse_args()

    # Prompt for passwords not supplied on the command line
    ca_pw = (args.ca_password or getpass.getpass("CA key password: ")).encode()
    srv_pw = (args.server_password or getpass.getpass("Server key password: ")).encode()
    cli_pw = (args.client_password or getpass.getpass("Client key password: ")).encode()

    if not ca_pw or not srv_pw or not cli_pw:
        print("ERROR: Passwords must not be empty.", file=sys.stderr)
        sys.exit(1)

    generate_pki(args.clients, ca_pw, srv_pw, cli_pw)


if __name__ == "__main__":
    main()
